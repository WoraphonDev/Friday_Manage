def table(p, cols, rows):
    th = "".join('<th class="%s"%s>%s<small>%s</small></th>' % (a, (' style="width:%dpx"' % w) if w else '', t, en) for t, en, a, w in cols)
    body = ""
    for r in rows:
        tds = ""
        for (t, en, a, w), v in zip(cols, r):
            cls = a + (" num" if a == "r" else "") + (" neg" if isinstance(v, str) and v.startswith("-") else "")
            tds += f'<td class="{cls.strip()}">{v}</td>'
        body += f"<tr>{tds}</tr>"
    return f"{pin(p)}<table><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table>"

def item(title, sub=""):
    return f"<b>{title}</b>" + (f'<div class="sub">{sub}</div>' if sub else "")

def totals(p, words, lines):
    out = ""
    for label, val, kind in lines:
        out += f'<div class="{kind}"><span>{label}</span><span class="num">{val}</span></div>'
    return f'{pin(p)}<div class="totals"><div class="words"><span class="lbl">จำนวนเงินตัวอักษร / Amount in words</span><br><b>({words})</b></div><div class="sum">{out}</div></div>'

def band(p, title, cells, extra=""):
    cs = "".join('<span><span class="lbl">%s</span><b%s>%s</b></span>' % (k, ' class="mono"' if m else '', v) for k, v, m in cells)
    ex = f'<span class="bandnote">{extra}</span>' if extra else ""
    return f'{pin(p)}<div class="band"><h5>{title}</h5><div class="cells">{cs}</div>{ex}</div>'

def notes(p, items, stamp=""):
    li = "".join(f"<li>{x}</li>" for x in items)
    return f'{pin(p)}<div class="sec">{stamp}<h5>หมายเหตุ / Notes</h5><ul>{li}</ul></div>'

def sign(p, left, right):
    def one(line, role, sub):
        return f'<div class="sig"><span class="line">{line}</span><span>{role}</span><span>{sub}</span></div>'
    return f'{pin(p, auto=True)}<div class="sign">{one(*left)}{one(*right)}</div>'

